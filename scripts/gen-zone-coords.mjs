// Usage: node scripts/gen-zone-coords.mjs <zone.tab> <tzdata.zi> <out.ts>
// Builds utils/zoneCoords.ts (IANA zone -> [lat, lon]) from the OS tz database.
import { readFileSync, writeFileSync } from 'node:fs';

const [zoneTabPath, tzdataPath, outPath] = process.argv.slice(2);
if (!zoneTabPath || !tzdataPath || !outPath) {
  throw new Error('Usage: gen-zone-coords.mjs <zone.tab> <tzdata.zi> <out.ts>');
}

const coords = {};
for (const line of readFileSync(zoneTabPath, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, iso, zone] = line.split('\t');
  const match =
    /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(
      iso ?? ''
    );
  if (!match || !zone) continue;
  // ISO 6709: sign, degrees (2 lat / 3 lon), minutes, optional seconds
  const [, latSign, latDeg, latMin, latSec, lonSign, lonDeg, lonMin, lonSec] =
    match;
  const lat =
    (latSign === '-' ? -1 : 1) *
    (Number(latDeg) + Number(latMin) / 60 + Number(latSec ?? 0) / 3600);
  const lon =
    (lonSign === '-' ? -1 : 1) *
    (Number(lonDeg) + Number(lonMin) / 60 + Number(lonSec ?? 0) / 3600);
  coords[zone] = [
    Math.round(lat * 10000) / 10000,
    Math.round(lon * 10000) / 10000,
  ];
}

for (const line of readFileSync(tzdataPath, 'utf8').split('\n')) {
  const [kind, target, alias] = line.split(' ');
  // WHY: zone.tab keeps per-country coords for merged zones (Oslo, Accra); links only fill gaps
  if (kind === 'L' && alias && coords[target] && !coords[alias])
    coords[alias] = coords[target];
}

const body = Object.keys(coords)
  .sort()
  .map((zone) => `  '${zone}': [${coords[zone].join(', ')}],`)
  .join('\n');

writeFileSync(
  outPath,
  `// Generated by scripts/gen-zone-coords.mjs from the IANA tz database (public domain). Do not edit.\n` +
    `const zoneCoords: Record<string, readonly [number, number]> = {\n${body}\n};\n\nexport default zoneCoords;\n`
);
